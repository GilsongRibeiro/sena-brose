/* TROCAR IDIOMA */

function changeLanguage(lang){

  document.querySelectorAll("[data-lang]").forEach(element => {

    const key = element.getAttribute("data-lang")

    if(translations[lang][key]){

      element.innerText = translations[lang][key]

    }

  })

}

/* PLACEHOLDERS DO FORMULÁRIO */

function updatePlaceholders(lang){

  document.querySelector("#name").placeholder =
  translations[lang].formName

  document.querySelector("#email").placeholder =
  translations[lang].formEmail

  document.querySelector("#message").placeholder =
  translations[lang].formMessage

}

/* BOTÃO FORM */

function updateFormButton(lang){

  document.querySelector("#formButton").innerText =
  translations[lang].formButton

}

